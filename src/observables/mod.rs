//! Навигационные наблюдаемые (observables) — измерения, формируемые на основе
//! результатов сопровождения спутниковых сигналов.
//!
//! Этот модуль является публичной точкой входа в подсистему observables.
//! Он объединяет специализированные подмодули, выполняет их реэкспорт и
//! предоставляет единый API для формирования навигационных наблюдаемых.
//!
//! # Структура модуля
//!
//! - [`base`] — агрегирование наблюдаемых и основной API (`Observable`,
//!   `ObservableSet`)
//! - [`pseudorange`] — вычисление псевдодальностей
//! - [`doppler`] — вычисление доплеровских измерений и псевдоскоростей
//! - [`cn0`] — оценка C/N₀ и вычисление весов измерений
//!
//! Большая часть логики находится в соответствующих подмодулях, тогда как
//! данный файл служит точкой входа и объединяет их в единый интерфейс.

pub mod base;
pub mod cn0;
pub mod doppler;
pub mod pseudorange;
