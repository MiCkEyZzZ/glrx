//! Tracking layer — DLL/FLL/PLL и многоканальное сопровождение спутников.
//!
//! # Структура
//!
//! ```text
//! tracking
//! ├── dll      — Delay Lock Loop: фаза/частота PRN-кода
//! ├── fll      — Frequency Lock Loop: грубый частотный захват
//! ├── pll      — Phase Lock Loop: фазовая синхронизация несущей
//! └── channel  — TrackingChannel / ChannelBank: многоканальное
//!                сопровождение, аллокация/деаллокация, метрики
//! ```
//!
//! # Связь между модулями
//!
//! `Fll` и `Pll` — независимые контуры без встроенного дублирования друг
//! друга: `Fll` выполняет только частотный захват и сигнализирует
//! `ready_for_pll`, после чего внешний код (как правило —
//! [`channel::TrackingChannel`]) создаёт `Pll` с финальной частотой через
//! `Fll::complete_handoff()`. `Dll` работает параллельно и независимо от
//! FLL/PLL, отслеживая фазу кода по тем же EPL-корреляциям.
//!
//! Для одновременного сопровождения нескольких спутников используйте
//! [`channel::ChannelBank`] — конфигурируемый пул каналов (8/16/32 и т.д.)
//! с аллокацией под результаты acquisition и автоматической деаллокацией
//! при потере lock.

